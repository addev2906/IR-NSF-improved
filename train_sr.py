"""
train_sr.py
-----------
Training script for Super-Resolution (SR) -- paper §IV-A, IR-NSF framework.

Paper §IV-A (SR task):
  Network:   EDSR [53] (64 feats, 16 blocks, scale x2/3/4).
  Loss:      Separable L1 in Fourier domain (IRNSFLoss, penalty='l1').
  Input:     Bicubic LR image.
  Target:    HR image + Gaussian noise sigma=10 (noisy target, generated on-the-fly).
  Optimizer: Adam lr=1e-4, LR halved every 200k steps.
  Data:      22988 DIV2K 480x480 patches (colour RGB).
  Metrics:   PSNR/SSIM on Y channel of YCbCr, borders cropped by scale factor.

Usage:
    python train_sr.py --train_dir data/DIV2K/patches_train \\
                       --val_dir   data/DIV2K/patches_val   \\
                       --scale 4
"""

from __future__ import annotations

import argparse
import csv
import time
from pathlib import Path
from typing import Optional

import torch
import torch.nn as nn
from torch.optim import Adam
from torch.optim.lr_scheduler import MultiStepLR
from torch.utils.data import DataLoader

from dataset import build_sr_dataloaders
from loss import IRNSFLoss
from model import build_edsr


# ---------------------------------------------------------------------------
# YCbCr PSNR / SSIM  (paper §IV-A: "PSNR and SSIM are measured on the Y
# channel of YCbCr, and an equal number of border pixels is ignored.")
# ---------------------------------------------------------------------------

def rgb_to_y(img: torch.Tensor) -> torch.Tensor:
    """
    Convert RGB image tensor to Y channel of YCbCr.

    Standard ITU-R BT.601 coefficients (same as EDSR paper [53]).

    Args:
        img: (B, 3, H, W) or (3, H, W) in [0, 1].

    Returns:
        Y channel (B, 1, H, W) or (1, H, W) in [0, 255] range
        (as used in SR PSNR computation).
    """
    if img.ndim == 3:
        img = img.unsqueeze(0)
    r, g, b = img[:, 0:1], img[:, 1:2], img[:, 2:3]
    y = 16.0 + 65.481 * r + 128.553 * g + 24.966 * b   # [0, 255]
    return y


def sr_psnr(pred: torch.Tensor, target: torch.Tensor, scale: int) -> float:
    """
    PSNR on Y channel with border crop (paper §IV-A SR metric).

    Args:
        pred   (B, 3, H, W): Predicted SR image in [0, 1].
        target (B, 3, H, W): Ground-truth HR image in [0, 1].
        scale (int): SR scale factor; border pixels to crop.

    Returns:
        Mean PSNR over the batch (float, dB).
    """
    # Crop borders
    pred_c   = pred  [:, :, scale:-scale, scale:-scale]
    target_c = target[:, :, scale:-scale, scale:-scale]

    # Y channel in [0, 255]
    pred_y   = rgb_to_y(pred_c).clamp(0, 255)
    target_y = rgb_to_y(target_c).clamp(0, 255)

    mse = ((pred_y - target_y) ** 2).mean(dim=[1, 2, 3])
    psnr = (10 * torch.log10(255.0 ** 2 / mse.clamp(min=1e-8))).mean().item()
    return psnr


# ---------------------------------------------------------------------------
# Training epoch
# ---------------------------------------------------------------------------

def train_one_epoch_sr(
    model:     nn.Module,
    loader:    DataLoader,
    criterion: IRNSFLoss,
    optimiser: torch.optim.Optimizer,
    scheduler: torch.optim.lr_scheduler._LRScheduler,
    device:    torch.device,
    epoch:     int,
    scale:     int,
    log_every: int = 100,
) -> dict:
    """
    One SR training epoch.

    Pair: LR input  +  noisy HR target (Gaussian sigma=10, generated by dataset).
    Loss: L1 Fourier (IRNSFLoss with penalty='l1').

    Returns:
        dict with 'train_loss' and 'train_psnr' averaged over batches.
    """
    model.train()
    total_loss = 0.0
    total_psnr = 0.0
    n_batches  = len(loader)
    t0         = time.time()

    for i, (lr_inp, noisy_hr) in enumerate(loader):
        lr_inp   = lr_inp.to(device, non_blocking=True)    # (B, 3, H/s, W/s)
        noisy_hr = noisy_hr.to(device, non_blocking=True)  # (B, 3, H, W)

        pred = model(lr_inp)                               # (B, 3, H, W)
        loss, info = criterion(pred, noisy_hr)

        optimiser.zero_grad()
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimiser.step()
        scheduler.step()

        psnr = sr_psnr(pred.detach(), noisy_hr, scale)
        total_loss += info["loss"]
        total_psnr += psnr

        if (i + 1) % log_every == 0:
            print(f"  Epoch {epoch:03d} [{i+1:4d}/{n_batches}]  "
                  f"Loss={info['loss']:.5f}  PSNR(Y)~={psnr:.2f}dB  "
                  f"LR={scheduler.get_last_lr()[0]:.2e}  "
                  f"({time.time()-t0:.1f}s)")

    return {"train_loss": total_loss / n_batches,
            "train_psnr": total_psnr / n_batches}


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------

@torch.no_grad()
def validate_sr(
    model:     nn.Module,
    loader:    DataLoader,
    criterion: IRNSFLoss,
    device:    torch.device,
    scale:     int,
) -> dict:
    """Validation: L1 Fourier loss + PSNR(Y) on val set."""
    model.eval()
    total_loss = 0.0
    total_psnr = 0.0
    n_batches  = len(loader)

    for lr_inp, noisy_hr in loader:
        lr_inp   = lr_inp.to(device, non_blocking=True)
        noisy_hr = noisy_hr.to(device, non_blocking=True)
        pred     = model(lr_inp)
        _, info  = criterion(pred, noisy_hr)
        total_loss += info["loss"]
        total_psnr += sr_psnr(pred, noisy_hr, scale)

    return {"val_loss": total_loss / n_batches,
            "val_psnr": total_psnr / n_batches}


# ---------------------------------------------------------------------------
# Checkpoint helpers
# ---------------------------------------------------------------------------

def save_checkpoint(state: dict, path: Path) -> None:
    torch.save(state, path)
    print(f"[train_sr] Checkpoint -> {path}")


def load_checkpoint(path: Path, model: nn.Module,
                    optimiser: Optional[torch.optim.Optimizer] = None) -> int:
    ckpt = torch.load(path, map_location="cpu")
    model.load_state_dict(ckpt["model"])
    if optimiser and "optimiser" in ckpt:
        optimiser.load_state_dict(ckpt["optimiser"])
    epoch = ckpt.get("epoch", 0)
    print(f"[train_sr] Loaded {path} (epoch {epoch})")
    return epoch


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def train_sr(args: argparse.Namespace) -> None:
    device = torch.device(f"cuda:{args.gpu}" if torch.cuda.is_available() else "cpu")
    print(f"[train_sr] Device: {device}  Scale: x{args.scale}")

    train_loader, val_loader = build_sr_dataloaders(
        train_patch_dir=args.train_dir,
        val_patch_dir=args.val_dir or None,
        scale=args.scale,
        batch_size=args.batch_size,
        num_workers=args.num_workers,
        target_sigma=args.target_sigma,
    )

    model = build_edsr(
        scale=args.scale,
        n_feats=args.n_feats,
        n_resblocks=args.n_resblocks,
        device=device,
    )

    # Paper uses L1 Fourier loss for SR
    criterion = IRNSFLoss(penalty="l1")
    print(f"[train_sr] Loss: IRNSFLoss(penalty=l1)")

    optimiser = Adam(model.parameters(), lr=args.lr, betas=(0.9, 0.999))

    steps_per_epoch = len(train_loader)
    decay_epochs    = max(1, args.decay_steps // steps_per_epoch)
    milestones      = [decay_epochs * (k + 1) for k in range(10)]
    scheduler = MultiStepLR(optimiser, milestones=milestones, gamma=0.5)
    print(f"[train_sr] LR halves every {decay_epochs} epochs ({args.decay_steps} steps)")

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    start_epoch = 0
    best_psnr   = 0.0
    if args.resume and Path(args.resume).exists():
        start_epoch = load_checkpoint(Path(args.resume), model, optimiser)

    log_path   = out_dir / "training_log_sr.csv"
    log_fields = ["epoch", "lr", "train_loss", "train_psnr", "val_loss", "val_psnr"]
    with open(log_path, "w", newline="") as f:
        csv.DictWriter(f, fieldnames=log_fields).writeheader()

    print(f"[train_sr] Training {args.epochs} epochs | log -> {log_path}")

    for epoch in range(start_epoch + 1, args.epochs + 1):
        print(f"\n=== Epoch {epoch}/{args.epochs} | LR={scheduler.get_last_lr()[0]:.2e} ===")

        t_metrics = train_one_epoch_sr(
            model, train_loader, criterion, optimiser, scheduler,
            device, epoch, scale=args.scale, log_every=args.log_every,
        )

        v_metrics: dict = {}
        if val_loader:
            v_metrics = validate_sr(model, val_loader, criterion, device, scale=args.scale)
            print(f"  Val  | Loss={v_metrics['val_loss']:.5f}  PSNR(Y)~={v_metrics['val_psnr']:.2f}dB")

        print(f"  Train| Loss={t_metrics['train_loss']:.5f}  PSNR(Y)~={t_metrics['train_psnr']:.2f}dB")

        row = {"epoch": epoch, "lr": scheduler.get_last_lr()[0]}
        row.update(t_metrics)
        row.update(v_metrics)
        with open(log_path, "a", newline="") as f:
            csv.DictWriter(f, fieldnames=log_fields).writerow(row)

        if epoch % args.save_every == 0:
            save_checkpoint(
                {"epoch": epoch, "model": model.state_dict(), "optimiser": optimiser.state_dict()},
                out_dir / f"sr_checkpoint_epoch{epoch:04d}.pt",
            )

        cur_psnr = v_metrics.get("val_psnr", t_metrics["train_psnr"])
        if cur_psnr > best_psnr:
            best_psnr = cur_psnr
            save_checkpoint(
                {"epoch": epoch, "model": model.state_dict(),
                 "optimiser": optimiser.state_dict(), "best_psnr": best_psnr},
                out_dir / "sr_best_model.pt",
            )
            print(f"  ** Best PSNR(Y): {best_psnr:.2f} dB **")

    print(f"\n[train_sr] Done. Best PSNR(Y): {best_psnr:.2f} dB | {out_dir}")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="IR-NSF Super-Resolution Training",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    g = p.add_argument_group("Data")
    g.add_argument("--train_dir",    required=True)
    g.add_argument("--val_dir",      default=None)
    g.add_argument("--batch_size",   type=int,   default=16)
    g.add_argument("--num_workers",  type=int,   default=4)
    g.add_argument("--target_sigma", type=float, default=10.0,
                   help="Gaussian sigma for noisy HR target (paper: 10)")

    g = p.add_argument_group("SR")
    g.add_argument("--scale",        type=int,   default=4, choices=[2, 3, 4],
                   help="SR scale factor")

    g = p.add_argument_group("Model (EDSR)")
    g.add_argument("--n_feats",      type=int,   default=64)
    g.add_argument("--n_resblocks",  type=int,   default=16)

    g = p.add_argument_group("Training")
    g.add_argument("--epochs",       type=int,   default=300)
    g.add_argument("--lr",           type=float, default=1e-4)
    g.add_argument("--decay_steps",  type=int,   default=200_000)
    g.add_argument("--gpu",          type=int,   default=0)
    g.add_argument("--resume",       default=None)
    g.add_argument("--out_dir",      default="checkpoints_sr")
    g.add_argument("--save_every",   type=int,   default=10)
    g.add_argument("--log_every",    type=int,   default=100)
    return p.parse_args()


if __name__ == "__main__":
    train_sr(parse_args())
